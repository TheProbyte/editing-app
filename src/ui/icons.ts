// Lumen's pixel icon set. Each icon is drawn on a small grid ('#' = pixel, '+' = half-tone
// pixel, anything else = empty) and turned into one crisp SVG path, so it stays sharp at
// any size and costs nothing to render.

function pix(art: string): string {
  const rows = art.trim().split('/').map((r) => r.trim());
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  let full = '';
  let half = '';
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; ) {
      const c = r[x];
      if (c !== '#' && c !== '+') {
        x++;
        continue;
      }
      let e = x;
      while (e < r.length && r[e] === c) e++;
      const d = `M${x} ${y}h${e - x}v1h${x - e}z`;
      if (c === '#') full += d;
      else half += d;
      x = e;
    }
  });
  // square viewBox centred on the art, so every icon sits on the same baseline
  const S = Math.max(w, h);
  const ox = (w - S) / 2, oy = (h - S) / 2;
  return `<svg viewBox="${ox} ${oy} ${S} ${S}" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">` +
    (half ? `<path d="${half}" opacity=".42"/>` : '') + `<path d="${full}"/></svg>`;
}

const mirror = (art: string) => art.trim().split('/').map((r) => [...r.trim()].reverse().join('')).join('/');
const transpose = (art: string) => {
  const rows = art.trim().split('/').map((r) => r.trim());
  const w = Math.max(...rows.map((r) => r.length));
  return Array.from({ length: w }, (_, x) => rows.map((r) => r[x] ?? '.').join('')).join('/');
};

